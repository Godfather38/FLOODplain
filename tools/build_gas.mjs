// Builds apps-script/WashWatch.gs: one file to paste into Google Apps Script.
// It contains the app's own rules (public/config.js, logic.js, engine.js) plus the
// alert service (apps-script/Code.gs), so texts use exactly the same ratings as the app.
// Usage: node tools/build_gas.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { transformSync } from 'esbuild';
import { parse } from 'acorn';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const strip = (src) => src
  .replace(/^import[\s\S]*?from\s+['"][^'"]+['"];\s*$/gm, '')
  .replace(/^export (const|function|class|let) /gm, '$1 ');
const routes = JSON.parse(read('public/data/routes.geojson')).features
  .map((f) => ({ properties: { id: f.properties.id, area: f.properties.area, name: f.properties.name, minutes: f.properties.minutes, km: f.properties.km } }));

const out = `// GENERATED by tools/build_gas.mjs from public/config.js, logic.js, engine.js and apps-script/Code.gs.
// Paste this whole file into one Apps Script project (https://script.new). Edit the sources, not this.

// ===== small stand-ins for browser features Apps Script lacks =====
if (typeof URLSearchParams === 'undefined') {
  globalThis.URLSearchParams = class {
    constructor(o) { this.o = o || {}; }
    toString() { return Object.keys(this.o).map((k) => encodeURIComponent(k) + '=' + encodeURIComponent(this.o[k])).join('&'); }
  };
}

// ===== public/config.js =====
${strip(read('public/config.js'))}
// ===== public/logic.js =====
${strip(read('public/logic.js'))}
// ===== public/engine.js =====
${strip(read('public/engine.js')).replace(/\bcfg\./g, 'CFG_.')}
const CFG_ = { AREAS, SOURCES, USGS_SITES, STALE_MS, SNAPSHOT_STALE_MS, RIVER, RAIN, RAIN_GAUGES, WASH, FAILURE_POINTS, RIVER_EARLY, CLOSURE_RADIUS_M, CLOSURE_BOUNDS, ROUTE_INFO };
const cfg = CFG_;
const ROUTE_FEATURES = ${JSON.stringify(routes)};

// ===== apps-script/Code.gs =====
${read('apps-script/Code.gs')}
`;
// Google Apps Script only understands older JavaScript (no ??=, numeric separators,
// optional chaining is risky), so lower everything to ES2019 and check it parses as such.
const lowered = transformSync(out, { target: 'es2019', format: 'esm', charset: 'utf8', legalComments: 'inline' }).code;
parse(lowered, { ecmaVersion: 2019, sourceType: 'script' });
writeFileSync(new URL('apps-script/WashWatch.gs', root), lowered);
console.log(`apps-script/WashWatch.gs: ${lowered.length} chars, parses as ES2019`);
